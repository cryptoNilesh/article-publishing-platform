
-- Article Publishing Platform
-- Database: PostgreSQL
-- Schema documentation matching JPA entity mappings

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(30) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    display_name VARCHAR(80),
    role VARCHAR(20) NOT NULL DEFAULT 'USER',
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    slug VARCHAR(250) NOT NULL UNIQUE,
    summary VARCHAR(500),
    content TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    published_at TIMESTAMP WITH TIME ZONE,
    author_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_articles_author
        FOREIGN KEY (author_id) REFERENCES users(id)
);

CREATE TABLE comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content TEXT NOT NULL,
    article_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    parent_comment_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_comments_article
        FOREIGN KEY (article_id) REFERENCES articles(id),

    CONSTRAINT fk_comments_author
        FOREIGN KEY (author_id) REFERENCES users(id),

    CONSTRAINT fk_comments_parent
        FOREIGN KEY (parent_comment_id) REFERENCES comments(id)
);

CREATE TABLE article_likes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_article_likes_article
        FOREIGN KEY (article_id) REFERENCES articles(id),

    CONSTRAINT fk_article_likes_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT uk_article_user_like
        UNIQUE (article_id, user_id)
);

CREATE TABLE article_tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id BIGINT NOT NULL,
    tagged_user_id BIGINT NOT NULL,
    tagged_by_user_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_article_tags_article
        FOREIGN KEY (article_id) REFERENCES articles(id),

    CONSTRAINT fk_article_tags_tagged_user
        FOREIGN KEY (tagged_user_id) REFERENCES users(id),

    CONSTRAINT fk_article_tags_tagged_by
        FOREIGN KEY (tagged_by_user_id) REFERENCES users(id),

    CONSTRAINT uk_article_tagged_user
        UNIQUE (article_id, tagged_user_id)
);

CREATE TABLE comment_tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comment_id BIGINT NOT NULL,
    tagged_user_id BIGINT NOT NULL,
    tagged_by_user_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_comment_tags_comment
        FOREIGN KEY (comment_id) REFERENCES comments(id),

    CONSTRAINT fk_comment_tags_tagged_user
        FOREIGN KEY (tagged_user_id) REFERENCES users(id),

    CONSTRAINT fk_comment_tags_tagged_by
        FOREIGN KEY (tagged_by_user_id) REFERENCES users(id),

    CONSTRAINT uk_comment_tagged_user
        UNIQUE (comment_id, tagged_user_id)
);

-- Useful indexes for common queries

CREATE INDEX idx_articles_author_id ON articles(author_id);
CREATE INDEX idx_comments_article_id ON comments(article_id);
CREATE INDEX idx_comments_parent_comment_id ON comments(parent_comment_id);
CREATE INDEX idx_article_likes_user_id ON article_likes(user_id);
CREATE INDEX idx_article_tags_tagged_user_id ON article_tags(tagged_user_id);
CREATE INDEX idx_comment_tags_tagged_user_id ON comment_tags(tagged_user_id);
